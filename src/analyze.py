# ===================================================================== C
say("\n## C. Sensitivity of the Access Gap Score\n")
scenarios = {
    "base_50_50":        (0.5, "providers_per_100k_2020_22"),
    "demand_heavy_70_30": (0.7, "providers_per_100k_2020_22"),
    "supply_heavy_30_70": (0.3, "providers_per_100k_2020_22"),
    "current_supply_2024": (0.5, "providers_per_100k_2024"),
}
sens = gap[["state", "state_name"]].copy()
for name, (w, col) in scenarios.items():
    sens[name] = 100 * (w * pct_rank(gap.unmet_need_pct)
                        + (1 - w) * pct_rank(gap[col], ascending=False))

base_top = set(sens.nlargest(10, "base_50_50").state)
say("| Scenario | Top-10 overlap with base | Rank correlation with base |")
say("|---|---:|---:|")
in_all = base_top.copy()
for name in scenarios:
    top10 = set(sens.nlargest(10, name).state)
    in_all &= top10
    r, _ = stats.spearmanr(sens.base_50_50, sens[name])
    say(f"| {name} | {len(base_top & top10)}/10 | {r:.2f} |")
sens["top10_in_all_scenarios"] = sens.state.isin(in_all)
say(f"\n- States in the top 10 under **every** scenario (most robust findings): "
    f"**{', '.join(sorted(in_all)) or 'none'}**")
sens.to_csv(EXPORT / "analysis_gap_sensitivity.csv", index=False)

# ===================================================================== D
say("\n## D. Do higher-paying states retain more providers?\n")
change = q("""
    SELECT state,
           sum(providers) FILTER (WHERE year = 2019) AS p2019,
           sum(providers) FILTER (WHERE year = 2024 AND bh_category <> 'Counselor / MFT') AS p2024_lfl
    FROM fct_state_supply GROUP BY state""")
change["lfl_change_pct"] = 100 * (change.p2024_lfl / change.p2019 - 1)
d = gap[["state", "psychotherapy_payment_index"]].merge(change, on="state")
rho3, p3, n3 = spearman(d.psychotherapy_payment_index, d.lfl_change_pct)
say(f"- 90837 payment index vs like-for-like provider change (n={n3}): {describe_corr(rho3, p3)}")
say(f"- Largest declines: " + ", ".join(
    f"{r.state} ({r.lfl_change_pct:+.0f}%)" for r in d.nsmallest(5, "lfl_change_pct").itertuples()))
say(f"- Smallest declines / growth: " + ", ".join(
    f"{r.state} ({r.lfl_change_pct:+.0f}%)" for r in d.nlargest(5, "lfl_change_pct").itertuples()))
d.to_csv(EXPORT / "analysis_state_change.csv", index=False)

fig, ax = plt.subplots(figsize=(8, 5))
ax.scatter(d.psychotherapy_payment_index, d.lfl_change_pct, alpha=0.7)
