"""
Phase 4 - Statistical Analysis
------------------------------
Reads the DuckDB warehouse and answers five questions:
  A. How much did the Medicare behavioral-health workforce change? (like-for-like)
  B. Is provider supply related to unmet need / counseling received? (Spearman)
  C. Is the Access Gap Score robust to weighting choices? (sensitivity analysis)
  D. Do states that pay more retain more providers? (Spearman)
  E. Which providers bill far outside their peers? (robust z-score outliers)
  F. Who has the most unmet need? (demographic breakdowns)

Outputs:
  docs/analysis_findings.md        auto-generated findings with real numbers
  docs/figures/*.png               charts for the README
  tableau/data/analysis_*.csv      extra tables for the dashboard

Usage:
    python src/analyze.py
"""
from pathlib import Path

import duckdb
import matplotlib
import numpy as np
import pandas as pd
from scipy import stats

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "data" / "warehouse.duckdb"
FIG = ROOT / "docs" / "figures"
EXPORT = ROOT / "tableau" / "data"
REPORT = ROOT / "docs" / "analysis_findings.md"
FIG.mkdir(parents=True, exist_ok=True)

con = duckdb.connect(str(DB), read_only=True)
q = lambda sql: con.execute(sql).df()  # noqa: E731
md: list[str] = ["# Analysis Findings\n",
                 "_Auto-generated by `src/analyze.py` from the DuckDB warehouse._\n"]


def say(text: str = "") -> None:
    print(text)
    md.append(text)


def spearman(x: pd.Series, y: pd.Series) -> tuple[float, float, int]:
    mask = x.notna() & y.notna()
    rho, p = stats.spearmanr(x[mask], y[mask])
    return float(rho), float(p), int(mask.sum())


def describe_corr(rho: float, p: float) -> str:
    strength = ("negligible" if abs(rho) < 0.1 else "weak" if abs(rho) < 0.3
                else "moderate" if abs(rho) < 0.5 else "strong")
    direction = "positive" if rho > 0 else "negative"
    sig = "statistically significant" if p < 0.05 else "not statistically significant"
    return f"{strength} {direction} (rho = {rho:.2f}, p = {p:.3f}, {sig} at 0.05)"


def pct_rank(s: pd.Series, ascending: bool = True) -> pd.Series:
    """Same definition as SQL PERCENT_RANK(): (rank - 1) / (n - 1)."""
    r = s.rank(method="min", ascending=ascending)
    return (r - 1) / (s.notna().sum() - 1)


# ===================================================================== A
say("## A. Workforce change, 2019 to 2024\n")
cat = q("SELECT * FROM mart_category_trend ORDER BY bh_category, year")
kpi = q("SELECT * FROM mart_national_kpis ORDER BY year")

p19 = cat.query("year == 2019").set_index("bh_category")["providers"]
p24 = cat.query("year == 2024").set_index("bh_category")["providers"]
legacy = [c for c in p19.index if p19[c] > 0]
lfl19, lfl24 = p19[legacy].sum(), p24[legacy].sum()

say(f"- All BH providers: {int(kpi.bh_providers.iloc[0]):,} (2019) to "
    f"{int(kpi.bh_providers.iloc[-1]):,} (2024), "
    f"{100 * (kpi.bh_providers.iloc[-1] / kpi.bh_providers.iloc[0] - 1):+.1f}%")
say(f"- Like-for-like (excluding Counselor / MFT, newly eligible in 2024): "
    f"{int(lfl19):,} to {int(lfl24):,}, {100 * (lfl24 / lfl19 - 1):+.1f}%")
say(f"- Total Medicare BH payment: ${kpi.payment_amt.iloc[0] / 1e9:.2f}B to "
    f"${kpi.payment_amt.iloc[-1] / 1e9:.2f}B; payment per service "
    f"${kpi.payment_per_service.iloc[0]:.2f} to ${kpi.payment_per_service.iloc[-1]:.2f}\n")

say("| Category | 2019 | 2024 | Change | CAGR |")
say("|---|---:|---:|---:|---:|")
for c in legacy:
    cagr = (p24[c] / p19[c]) ** (1 / 5) - 1
    say(f"| {c} | {int(p19[c]):,} | {int(p24[c]):,} | {100 * (p24[c] / p19[c] - 1):+.1f}% "
        f"| {100 * cagr:+.1f}%/yr |")

fig, ax = plt.subplots(figsize=(8, 4.5))
for c in legacy:
    s = cat[cat.bh_category == c]
    ax.plot(s.year, 100 * s.providers / s.providers.iloc[0], marker="o", label=c)
ax.axhline(100, color="grey", lw=0.8, ls="--")
ax.set(title="Medicare behavioral-health providers (2019 = 100)",
       xlabel="", ylabel="Index")
ax.legend(frameon=False)
fig.tight_layout()
fig.savefig(FIG / "workforce_index.png", dpi=150)
plt.close(fig)

# ===================================================================== B
say("\n## B. Is provider supply related to mental-health outcomes?\n")
gap = q("SELECT * FROM mart_state_gap")
rho, p, n = spearman(gap.providers_per_100k_2020_22, gap.unmet_need_pct)
say(f"- Providers per 100k vs **unmet counseling need** (n={n}): {describe_corr(rho, p)}")
rho2, p2, _ = spearman(gap.providers_per_100k_2020_22, gap.received_counseling_pct)
say(f"- Providers per 100k vs **received counseling**: {describe_corr(rho2, p2)}")
say("- Interpretation: correlation across 51 states is descriptive, not causal. "
    "Medicare billing covers only part of each state's mental-health workforce.")

fig, ax = plt.subplots(figsize=(8, 6))
top = gap.nsmallest(10, "access_gap_rank")
ax.scatter(gap.providers_per_100k_2020_22, gap.unmet_need_pct, alpha=0.6)
ax.scatter(top.providers_per_100k_2020_22, top.unmet_need_pct, color="crimson",
           label="Top 10 access gap")
