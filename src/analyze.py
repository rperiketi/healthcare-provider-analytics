# ===================================================================== E
say("\n## E. Billing outliers (2024, robust z-score within provider type)\n")
prov = q("""SELECT npi, provider_type, bh_category, state, tot_benes, tot_services,
                   tot_payment_amt, payment_per_service
            FROM mart_provider_detail
            WHERE year = 2024 AND tot_services > 0 AND tot_payment_amt > 0""")
prov["services_per_bene"] = prov.tot_services / prov.tot_benes


def robust_z(s: pd.Series) -> pd.Series:
    x = np.log(s)
    med = x.median()
    mad = (x - med).abs().median()
    return 0.6745 * (x - med) / mad if mad > 0 else pd.Series(0.0, index=s.index)


for metric in ["payment_per_service", "services_per_bene"]:
    prov[f"z_{metric}"] = prov.groupby("provider_type")[metric].transform(robust_z)
prov["is_outlier"] = (prov.z_payment_per_service.abs() > 3.5) | (prov.z_services_per_bene.abs() > 3.5)

say(f"- Method: log-transform, then median/MAD z-score per provider type; |z| > 3.5 flagged "
    "(Iglewicz & Hoaglin). Robust to the skew that breaks mean/std z-scores.")
say(f"- Flagged {int(prov.is_outlier.sum()):,} of {len(prov):,} providers "
    f"({100 * prov.is_outlier.mean():.2f}%)\n")
say("| Category | Providers | Flagged | % |")
say("|---|---:|---:|---:|")
for c, g in prov.groupby("bh_category"):
    say(f"| {c} | {len(g):,} | {int(g.is_outlier.sum()):,} | {100 * g.is_outlier.mean():.2f}% |")
say("\n- These are statistical outliers for review, **not** evidence of fraud: case mix, "
    "facility billing and group practices can all explain unusual patterns.")
prov[prov.is_outlier].sort_values("z_payment_per_service", key=abs, ascending=False) \
    .to_csv(EXPORT / "analysis_provider_outliers.csv", index=False)

# ===================================================================== F
say("\n## F. Who has the most unmet need? (CDC, Aug 2020 - May 2022)\n")
grp = q("SELECT * FROM mart_demand_by_group")
for g in sorted(grp.group_name.unique()):
    if g == "National Estimate":
        continue
    piv = grp[grp.group_name == g].pivot_table(index="subgroup", columns="indicator",
                                               values="avg_pct")
    if "Unmet Counseling Need" not in piv:
        continue
    piv = piv.sort_values("Unmet Counseling Need", ascending=False)
    hi, lo = piv.index[0], piv.index[-1]
    say(f"- **{g}**: highest unmet need = {hi} ({piv.iloc[0]['Unmet Counseling Need']:.1f}%), "
        f"lowest = {lo} ({piv.iloc[-1]['Unmet Counseling Need']:.1f}%)")

